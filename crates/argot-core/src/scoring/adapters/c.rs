/// Parse C `source` into a tree-sitter `Tree` (reused per-thread parser).
fn parse(source: &str) -> Tree {
    crate::scoring::ts_parse::parse(source, Language::C)
        .expect("tree-sitter parse never returns None without a timeout")
}

/// Collect every descendant of `node` (pre-order, excluding `node` itself).
fn descendants<'a>(node: Node<'a>) -> Vec<Node<'a>> {
    let mut out = Vec::new();
    let mut cursor = node.walk();
    fn go<'a>(node: Node<'a>, out: &mut Vec<Node<'a>>) {
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            out.push(child);
            go(child, out);
        }
    }
    for child in node.children(&mut cursor) {
        out.push(child);
        go(child, &mut out);
    }
    out
}

/// Direct children of `node` as a `Vec`.
fn children<'a>(node: Node<'a>) -> Vec<Node<'a>> {
    let mut cursor = node.walk();
    node.children(&mut cursor).collect()
}

/// Direct children of `node` whose field name is `field` (a declaration can
/// carry several `declarator` fields, which `child_by_field_name` cannot
/// express — hence the manual cursor walk).
fn field_children<'a>(node: Node<'a>, field: &str) -> Vec<Node<'a>> {
    let mut out = Vec::new();
    let mut cursor = node.walk();
    if cursor.goto_first_child() {
        loop {
            if cursor.field_name() == Some(field) {
                out.push(cursor.node());
            }
            if !cursor.goto_next_sibling() {
                break;
            }
        }
    }
    out
}

fn node_text<'a>(node: Node, source: &'a str) -> &'a str {
    &source[node.byte_range()]
}

/// Strip the surrounding `<...>` from a `system_lib_string` node's text.
fn strip_angle(text: &str) -> &str {
    let b = text.as_bytes();
    if b.len() >= 2 && b[0] == b'<' && b[b.len() - 1] == b'>' {
        &text[1..text.len() - 1]
    } else {
        text
    }
}

/// Strip surrounding double quotes from a `string_literal` node's text.
fn strip_quotes(text: &str) -> &str {
    let b = text.as_bytes();
    if b.len() >= 2 && b[0] == b'"' && b[b.len() - 1] == b'"' {
        &text[1..text.len() - 1]
    } else {
        text
    }
}

/// External-module name for a `<...>` include: the header path up to the first
/// `/` (`stdio.h` stays whole; `openssl/ssl.h` → `openssl`).
fn system_module(header: &str) -> &str {
    header.split('/').next().unwrap_or(header)
}

/// Base identifier of a quoted header path: the last path segment without its
/// extension (`net/conn.h` → `conn`, `foo.h` → `foo`).
fn header_base(header: &str) -> &str {
    let last = header.rsplit('/').next().unwrap_or(header);
    match last.rfind('.') {
        Some(i) if i > 0 => &last[..i],
        _ => last,
    }
}

/// `(is_system, header_text)` for a `preproc_include` `path` node, or `None`.
fn include_path(path: Node, source: &str) -> Option<(bool, String)> {
    match path.kind() {
        "system_lib_string" => Some((true, strip_angle(node_text(path, source)).to_string())),
        "string_literal" => Some((false, strip_quotes(node_text(path, source)).to_string())),
        _ => None,
    }
}

/// Drill through pointer/array/parenthesized declarators to the innermost
/// `function_declarator`, then return its declared name — used for both
/// `function_definition`s and top-level prototype `declaration`s.
fn declared_function_name(decl: Node, source: &str) -> Option<String> {
    let mut node = decl;
    loop {
        match node.kind() {
            "function_declarator" => {
                let inner = node.child_by_field_name("declarator")?;
                return plain_identifier(inner, source);
            }
            "pointer_declarator" | "array_declarator" | "parenthesized_declarator" => {
                node = node.child_by_field_name("declarator")?;
            }
            _ => return None,
        }
    }
}

/// The identifier a plain (non-function) declarator ultimately binds, drilling
/// through `init_declarator` / pointer / array / parenthesized wrappers.
/// Returns `None` for a `function_declarator` (that is a callable, not a value).
fn plain_identifier(decl: Node, source: &str) -> Option<String> {
    let mut node = decl;
    loop {
        match node.kind() {
            "identifier" | "field_identifier" | "type_identifier" => {
                return Some(node_text(node, source).to_string());
            }
            "init_declarator"
            | "pointer_declarator"
            | "array_declarator"
            | "parenthesized_declarator" => {
                node = node.child_by_field_name("declarator")?;
            }
            _ => return None,
        }
    }
}

/// True if ≥80% of an `initializer_list`'s immediate named values are literal
/// data (or nested initializer lists). Empty lists return true (conservative).
fn is_initializer_literal_dominant(node: Node) -> bool {
    let values: Vec<Node> = children(node)
        .into_iter()
        .filter(|c| c.is_named())
        .collect();
    if values.is_empty() {
        return true;
    }
    let literal = values
        .iter()
        .filter(|v| C_VALUE_LITERAL_TYPES.contains(&v.kind()))
        .count();
    (literal as f64) / (values.len() as f64) >= 0.8
}

/// Add row spans (0-indexed) of top-level data-literal declarations to `rows` —
/// `T name[] = { ... };` where the initializer is literal-dominant.
fn collect_c_data_rows(root: Node, rows: &mut HashSet<usize>) {
    for child in children(root) {
        if child.kind() != "declaration" {
            continue;
        }
        for decl in field_children(child, "declarator") {
            if decl.kind() != "init_declarator" {
                continue;
            }
            let Some(value) = decl.child_by_field_name("value") else {
                continue;
            };
            if value.kind() == "initializer_list" && is_initializer_literal_dominant(value) {
                for r in child.start_position().row..=child.end_position().row {
                    rows.insert(r);
                }
            }
        }
    }
}

/// Build the dotted callee for a `call_expression`, or `None` when the chain
/// bottoms out at something that is neither an identifier nor a nested call.
fn extract_c_callee(call_node: Node, src: &[u8]) -> Option<String> {
    let mut callee = call_node.child_by_field_name("function")?;
    let mut parts: Vec<String> = Vec::new();
    while callee.kind() == "field_expression" {
        let field = callee.child_by_field_name("field")?;
        let arg = callee.child_by_field_name("argument")?;
        parts.insert(0, byte_text(field, src));
        callee = arg;
    }
    if callee.kind() == "identifier" {
        parts.insert(0, byte_text(callee, src));
        Some(parts.join("."))
    } else if callee.kind() == "call_expression" {
        parts.insert(0, "<call>".to_string());
        Some(parts.join("."))
    } else {
        None
    }
}

fn byte_text(node: Node, src: &[u8]) -> String {
    let r = node.byte_range();
    if r.is_empty() {
        String::new()
    } else {
        String::from_utf8_lossy(&src[r]).into_owned()
    }
}

/// `CAdapter` — the language adapter for `.c` / `.h` sources.
#[derive(Debug, Default)]
pub struct CAdapter {
    noise: HashSet<String>,
}

impl CAdapter {
    pub fn new() -> Self {
        Self {
            noise: NOISE.iter().map(|s| (*s).to_string()).collect(),
        }
    }

    /// External (`<...>`) module names imported via `#include`. Quoted
    /// (`"..."`) includes are repo-internal and are excluded here (they surface
    /// through `internal_import_bindings`).
    pub fn extract_imports(&self, source: &str) -> HashSet<String> {
        let tree = parse(source);
        let mut out = HashSet::new();
        for node in descendants(tree.root_node()) {
            if node.kind() != "preproc_include" {
                continue;
            }
            let Some(path) = node.child_by_field_name("path") else {
                continue;
            };
            if let Some((true, header)) = include_path(path, source) {
                let module = system_module(&header);
                if !module.is_empty() {
                    out.insert(module.to_string());
                }
            }
        }
        out
    }

    /// Like `extract_imports` but each module carries its `(spec, line,
    /// col_start, col_end)` span. Line 1-indexed; columns 0-indexed byte
    /// offsets covering the module text (skipping the opening `<`).
    /// Sorted by `(line, col_start, spec)`.
    pub fn extract_imports_with_spans(&self, source: &str) -> Vec<(String, usize, usize, usize)> {
        let tree = parse(source);
        let mut out: Vec<(String, usize, usize, usize)> = Vec::new();
        for node in descendants(tree.root_node()) {
            if node.kind() != "preproc_include" {
                continue;
            }
            let Some(path) = node.child_by_field_name("path") else {
                continue;
            };
            if let Some((true, header)) = include_path(path, source) {
                let module = system_module(&header).to_string();
                if module.is_empty() {
                    continue;
                }
                let line = path.start_position().row + 1;
                // Skip the opening `<` so the underline lands on the module.
                let col_start = path.start_position().column + 1;
                let col_end = col_start + module.len();
                out.push((module, line, col_start, col_end));
            }
        }
        out.sort_by(|a, b| (a.1, a.2, &a.0).cmp(&(b.1, b.2, &b.0)));
        out
    }

    /// C has no package manifest with owned module names — internal neighbours
    /// are discovered from quoted includes at fit time, so there are no
    /// exact/prefix rules (mirrors the Python adapter).
    pub fn resolve_repo_modules(&self, _repo_root: &Path) -> RepoModules {
        RepoModules::default()
    }

    /// Names the source binds to callable definitions — `function_definition`
    /// names, top-level prototype `declaration`s, `typedef` names, and named
    /// `struct` specifiers. Feeds local-binding attestation: code calling what
    /// it defines is not foreign voice.
    pub fn callable_definitions(&self, source: &str) -> HashSet<String> {
        let tree = parse(source);
        let mut out = HashSet::new();
        for node in descendants(tree.root_node()) {
            match node.kind() {
                "function_definition" => {
                    if let Some(decl) = node.child_by_field_name("declarator") {
                        if let Some(name) = declared_function_name(decl, source) {
                            out.insert(name);
                        }
                    }
                }
                "declaration" => {
                    for decl in field_children(node, "declarator") {
                        if let Some(name) = declared_function_name(decl, source) {
                            out.insert(name);
                        }
                    }
                }
                "type_definition" => {
                    for decl in field_children(node, "declarator") {
                        if decl.kind() == "type_identifier" {
                            out.insert(node_text(decl, source).to_string());
                        }
                    }
                }
                "struct_specifier" | "union_specifier" | "enum_specifier" => {
                    if let Some(name) = node.child_by_field_name("name") {
                        out.insert(node_text(name, source).to_string());
                    }
                }
                _ => {}
            }
        }
        out
    }

    /// Names bound by repo-internal (quoted) includes: the header base
    /// identifier (`#include "net/conn.h"` → `conn`). C includes bind no
    /// identifiers we can name precisely, so this is a deliberately weak proxy
    /// marking the `"..."` neighbourhood as not-foreign.
    pub fn internal_import_bindings(&self, source: &str) -> HashSet<String> {
        let tree = parse(source);
        let mut out = HashSet::new();
        for node in descendants(tree.root_node()) {
            if node.kind() != "preproc_include" {
                continue;
            }
            let Some(path) = node.child_by_field_name("path") else {
                continue;
            };
            if let Some((false, header)) = include_path(path, source) {
                let base = header_base(&header);
                if !base.is_empty() {
                    out.insert(base.to_string());
                }
            }
        }
        out
    }

    /// Every locally bound value name — variable `declaration` declarators and
    /// `parameter_declaration` names. Function prototypes are skipped (they are
    /// callables, reported by `callable_definitions`).
    pub fn value_bindings(&self, source: &str) -> HashSet<String> {
        let tree = parse(source);
        let mut out = HashSet::new();
        for node in descendants(tree.root_node()) {
            match node.kind() {
                "declaration" => {
                    for decl in field_children(node, "declarator") {
                        if let Some(name) = plain_identifier(decl, source) {
                            out.insert(name);
                        }
                    }
                }
                "parameter_declaration" => {
                    if let Some(decl) = node.child_by_field_name("declarator") {
                        if let Some(name) = plain_identifier(decl, source) {
                            out.insert(name);
                        }
                    }
                }
                _ => {}
            }
        }
        out
    }

    /// True if the file is overwhelmingly top-level data literals (static
    /// tables/arrays), threshold 0.65 of non-blank lines.
    pub fn is_data_dominant(&self, source: &str) -> bool {
        if source.trim().is_empty() {
            return false;
        }
        let tree = parse(source);
        let total_nonblank = splitlines(source)
            .iter()
            .filter(|line| !line.trim().is_empty())
            .count();
        if total_nonblank == 0 {
            return false;
        }
        let mut rows: HashSet<usize> = HashSet::new();
        collect_c_data_rows(tree.root_node(), &mut rows);
        (rows.len() as f64) / (total_nonblank as f64) > DATA_DOMINANT_THRESHOLD
    }

    /// 1-indexed line numbers covered by top-level data-literal declarations.
    pub fn data_literal_lines(&self, source: &str) -> HashSet<usize> {
        if source.trim().is_empty() {
            return HashSet::new();
        }
        let tree = parse(source);
        let mut rows: HashSet<usize> = HashSet::new();
        collect_c_data_rows(tree.root_node(), &mut rows);
        rows.into_iter().map(|r| r + 1).collect()
    }

    /// True if a comment in the first `HEADER_LINE_LIMIT` lines carries an
    /// auto-generation marker (case-insensitive), or a strong DO-NOT-EDIT
    /// marker within the first 10 lines.
    pub fn is_auto_generated(&self, source: &str) -> bool {
        if source.is_empty() {
            return false;
        }
        let tree = parse(source);
        for node in descendants(tree.root_node()) {
            if node.kind() != "comment" {
                continue;
            }
            let line_index = node.start_position().row;
            if line_index >= HEADER_LINE_LIMIT {
                continue;
            }
            let text = node_text(node, source).to_lowercase();
            if line_index < 10 && STRONG_FIRST_10_MARKERS.iter().any(|m| text.contains(m)) {
                return true;
            }
            let hit = GENERIC_MARKERS
                .iter()
                .chain(DO_NOT_EDIT_MARKERS.iter())
                .chain(TOOL_MARKERS.iter())
                .any(|m| text.contains(m));
            if hit {
                return true;
            }
        }
        false
    }

    /// 1-indexed inclusive `(start_line, end_line)` spans for top-level
    /// `function_definition`s with a `compound_statement` body.
    pub fn enumerate_sampleable_ranges(&self, source: &str) -> Vec<(usize, usize)> {
        let tree = parse(source);
        let mut ranges = Vec::new();
        for child in children(tree.root_node()) {
            if child.kind() != "function_definition" {
                continue;
            }
            if child.child_by_field_name("body").map(|b| b.kind()) == Some("compound_statement") {
                ranges.push((child.start_position().row + 1, child.end_position().row + 1));
            }
        }
        ranges
    }

    /// 1-indexed line numbers covered by comments (line `//` and block
    /// `/* */`). C has no docstring concept; all prose is in comments.
    pub fn prose_line_ranges(&self, source: &str) -> HashSet<usize> {
        let tree = parse(source);
        let mut rows: HashSet<usize> = HashSet::new();
        for node in descendants(tree.root_node()) {
            if node.kind() == "comment" {
                let start = node.start_position().row + 1;
                let end = node.end_position().row + 1;
                for r in start..=end {
                    rows.insert(r);
                }
            }
        }
        rows
    }

    /// C keywords + primitive types — noise tokens filtered out of the
    /// repo-wide identifier vocabulary.
    pub fn identifier_noise(&self) -> &HashSet<String> {
        &self.noise
    }
}

