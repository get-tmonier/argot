//! C language adapter.
//!
//! Behaviour-preserving sibling of `python.rs` / `typescript.rs`: the same
//! manual `TreeCursor` / `child_by_field_name` traversal style over the pinned
//! tree-sitter-c grammar.
//!
//! C is structurally poorer than the brace languages for voice signal:
//! - There is no exception-handling construct, so the except-ratio primitive
//!   is undefined for C (handled in that scorer, not here).
//! - There is no object/method receiver — a `call_expression`'s callee is a
//!   bare function name (or a `field_expression` for a function-pointer call
//!   such as `obj->fn()`). We build a dotted callee for the latter but keep it
//!   simple; the call-receiver signal is inherently weaker for C. We lean on
//!   `#include` imports and local definitions instead.
//!
//! Import model: `#include <stdio.h>` (a `system_lib_string`) is an
//! external/system module — its module name is the header path up to the first
//! `/` (`stdio.h` stays whole; `openssl/ssl.h` → `openssl`). `#include "foo.h"`
//! (a `string_literal`) is repo-internal and is surfaced through
//! `internal_import_bindings`, not `extract_imports` — mirroring how the
//! TypeScript adapter excludes relative specifiers.

