/// Which vocabulary a declared migration names. Mirrors the voice model's
/// supersession kinds without the engine depending on any rule crate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum MigrationKind {
    #[default]
    Import,
    Callee,
}

/// One declared migration (`[[migration]]`): the repo is moving from `from`
/// to `to`. New code using `from` raises the `superseded` rule, and `to`
/// never reads as a foreign pattern — effective at check time, no refit
/// needed. The declared counterpart of a mined supersession: the user states
/// a migration before history shows enough signal, or codifies one argot
/// surfaced.
#[derive(Debug, Clone, PartialEq)]
pub struct MigrationRule {
    pub from: String,
    pub to: String,
    /// Why the repo is migrating — rendered as the finding's evidence.
    pub reason: String,
    pub kind: MigrationKind,
}

/// The validated `[[migration]]` set plus per-entry validation notes.
#[derive(Debug, Clone, Default)]
pub struct MigrationsFile {
    pub active: Vec<MigrationRule>,
    pub warnings: Vec<String>,
}

/// Validate raw `[[migration]]` tables: `from`, `to`, and `reason` are
/// mandatory; `kind` is `"import"` (default) or `"callee"`. One bad entry
/// warns and is skipped — never a parse failure (the `[[mute]]` discipline).
fn build_migrations(raw: Vec<RawMigration>) -> MigrationsFile {
    let mut out = MigrationsFile::default();
    for (i, m) in raw.into_iter().enumerate() {
        let nth = i + 1;
        let (Some(from), Some(to)) = (m.from.clone(), m.to.clone()) else {
            out.warnings.push(format!(
                "argot.toml: [[migration]] #{nth}: 'from' and 'to' are required — ignored"
            ));
            continue;
        };
        let Some(reason) = m.reason.clone().filter(|r| !r.trim().is_empty()) else {
            out.warnings.push(format!(
                "argot.toml: [[migration]] #{nth} ({from} -> {to}): a reason is required — ignored"
            ));
            continue;
        };
        let kind = match m.kind.as_deref() {
            None | Some("import") => MigrationKind::Import,
            Some("callee") => MigrationKind::Callee,
            Some(other) => {
                out.warnings.push(format!(
                    "argot.toml: [[migration]] #{nth} ({from} -> {to}): unknown kind '{other}' \
                     (valid: \"import\", \"callee\") — ignored"
                ));
                continue;
            }
        };
        if from == to {
            out.warnings.push(format!(
                "argot.toml: [[migration]] #{nth}: 'from' and 'to' are both '{from}' — ignored"
            ));
            continue;
        }
        out.active.push(MigrationRule {
            from,
            to,
            reason,
            kind,
        });
    }
    out
}

/// The resolved argot configuration (`argot.toml` ⊕ `argot.local.toml`).
#[derive(Debug, Clone)]
pub struct ArgotConfig {
    pub exclude: ExcludeConfig,
    pub detect: DetectConfig,
    /// Validated `[rules]` layer from the committed `argot.toml`.
    pub rules_committed: Vec<RulesLayer>,
    /// Validated `[rules]` layer from the personal `argot.local.toml` —
    /// applied after the committed layer, refused for locked rules.
    pub rules_local: Vec<RulesLayer>,
    /// Per-selector path scopes from `[rules]` inline tables (`include` /
    /// `exclude` globs) — applies to **every** rule, built-in or custom: a
    /// finding whose file falls outside its rule's (or group's) scope is
    /// dropped. Distinct from a custom rule's *manifest* include/exclude,
    /// which also decides which files the rule even runs on (incl. unscored).
    pub rule_scopes: Vec<(String, crate::rules::RuleScope)>,
    /// Selectors locked by the committed `argot.toml` (inline-table form:
    /// `layering = { severity = "error", locked = true }`). Locked rules
    /// freeze at the committed severity and refuse every runtime suppression
    /// surface; only the committed file — a reviewable diff — can unlock.
    pub rule_locks: Vec<String>,
    /// `[update].check` — false opts out of the passive update notice.
    pub update_check: bool,
    /// `[fit].auto-refresh` — false opts out of the background refit when the
    /// model has drifted behind accepted history.
    pub fit_auto_refresh: bool,
    /// `[fit].refresh-after` — accepted in-scope commits since the fit before
    /// the background refresh (and check's drift warning) considers the voice
    /// stale. Clamped to ≥ 1.
    pub fit_refresh_after: usize,
    /// `[fit].refresh-from` — anchor the refresh on the default branch
    /// (feature-branch commits never train the voice) or on the current one.
    pub fit_refresh_from: FitRefreshFrom,
    /// Raw `[[mute]]` tables, validated on demand by [`ArgotConfig::mutes`].
    mutes: Vec<RawMute>,
    /// Raw `[[migration]]` tables, validated on demand by
    /// [`ArgotConfig::migrations`].
    migrations: Vec<RawMigration>,
    /// True when an `argot.toml` (or local) backed these values.
    pub from_file: bool,
    /// True when a config file existed but could not be parsed at all, so the
    /// whole document degraded to defaults. Distinct from [`Self::warnings`],
    /// which also carries per-entry notes ("unknown rule 'x' — ignored") that
    /// leave the rest of the config perfectly usable. A consumer that must fail
    /// open on an unreadable config — the pre-write hook — keys off this, not
    /// off the warning list: a typo in one `[[mute]]` should not take down a
    /// guardrail that never reads mutes.
    pub degraded: bool,
    /// Parse-level notes (malformed config file) for stderr.
    pub warnings: Vec<String>,
}

impl Default for ArgotConfig {
    fn default() -> Self {
        ArgotConfig {
            exclude: ExcludeConfig::default(),
            detect: DetectConfig::default(),
            rules_committed: Vec::new(),
            rules_local: Vec::new(),
            rule_scopes: Vec::new(),
            rule_locks: Vec::new(),
            update_check: true,
            fit_auto_refresh: true,
            fit_refresh_after: DEFAULT_FIT_REFRESH_AFTER,
            fit_refresh_from: FitRefreshFrom::default(),
            mutes: Vec::new(),
            migrations: Vec::new(),
            from_file: false,
            degraded: false,
            warnings: Vec::new(),
        }
    }
}

/// On-disk shape for serde reads.
#[derive(Debug, Clone, Default, Deserialize)]
struct RawConfig {
    #[serde(default)]
    exclude: RawExclude,
    #[serde(default)]
    detect: RawDetect,
    /// `[rules]` table: rule/group name → severity. Values are kept loose
    /// (`toml::Value`) so one bad entry warns instead of failing the file.
    #[serde(default)]
    rules: BTreeMap<String, toml::Value>,
    #[serde(default)]
    update: RawUpdate,
    #[serde(default)]
    fit: RawFit,
    /// `[[mute]]` array-of-tables.
    #[serde(default)]
    mute: Vec<RawMute>,
    /// `[[migration]]` array-of-tables.
    #[serde(default)]
    migration: Vec<RawMigration>,
}

/// Permissive on-disk shape: every field optional so one malformed
/// `[[migration]]` is a warning, not a parse failure for the whole config.
#[derive(Debug, Clone, Default, Deserialize)]
struct RawMigration {
    from: Option<String>,
    to: Option<String>,
    reason: Option<String>,
    kind: Option<String>,
}

#[derive(Debug, Clone, Default, Deserialize)]
struct RawExclude {
    recommended: Option<Vec<String>>,
    #[serde(default)]
    paths: Vec<String>,
    #[serde(rename = "check-only")]
    check_only: Option<Vec<String>>,
}

#[derive(Debug, Clone, Default, Deserialize)]
struct RawUpdate {
    check: Option<bool>,
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
struct RawFit {
    auto_refresh: Option<bool>,
    refresh_after: Option<u32>,
    refresh_from: Option<String>,
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
struct RawDetect {
    data_threshold: Option<f64>,
    generated_markers: Option<Vec<String>>,
}

/// Read + parse one config file. `Ok(None)` when the file is absent; `Err` with
/// a human note when it exists but is malformed (caller degrades gracefully).
fn read_raw(path: &Path) -> Result<Option<RawConfig>, String> {
    let content = match std::fs::read_to_string(path) {
        Ok(c) => c,
        Err(_) => return Ok(None),
    };
    match toml::from_str::<RawConfig>(&content) {
        Ok(raw) => Ok(Some(raw)),
        Err(e) => Err(format!(
            "{}: not valid TOML — ignored ({})",
            path.display(),
            e.message()
        )),
    }
}

impl ArgotConfig {
    /// Load `<repo_root>/argot.toml` and `argot.local.toml`, merged: scalars —
    /// local wins; lists (`paths`, `generated-markers`, `[[mute]]`) — appended.
    /// Absent files fall back to defaults; a malformed file degrades to defaults
    /// with a warning rather than failing the run.
    pub fn load(repo_root: &Path) -> Self {
        Self::load_with(repo_root, Registry::builtin())
    }

    /// [`ArgotConfig::load`] validating `[rules]` keys against a run
    /// vocabulary (built-ins + the repo's custom rules).
    pub fn load_with(repo_root: &Path, registry: &Registry) -> Self {
        let mut warnings = Vec::new();
        let mut degraded = false;
        let mut collect = |path: &Path| match read_raw(path) {
            Ok(raw) => raw,
            Err(w) => {
                warnings.push(w);
                degraded = true;
                None
            }
        };
        let base = collect(&repo_root.join(CONFIG_FILE));
        let local = collect(&repo_root.join(LOCAL_CONFIG_FILE));
        let from_file = base.is_some() || local.is_some();
        let base = base.unwrap_or_default();
        let local = local.unwrap_or_default();

        // [exclude]: recommended and check-only — the base list (or the built-in
        // default when omitted) plus any local extras; paths — appended.
        let mut recommended = base
            .exclude
            .recommended
            .unwrap_or_else(default_recommended_patterns);
        if let Some(extra) = local.exclude.recommended {
            recommended.extend(extra);
        }
        let mut paths = base.exclude.paths;
        paths.extend(local.exclude.paths);
        let mut check_only = base
            .exclude
            .check_only
            .unwrap_or_else(default_check_only_patterns);
        if let Some(extra) = local.exclude.check_only {
            check_only.extend(extra);
        }

        // [detect]: data-threshold — local wins; generated-markers — the base
        // list (or the built-in default when omitted) plus any local extras.
        let data_threshold = local
            .detect
            .data_threshold
            .or(base.detect.data_threshold)
            .unwrap_or(DEFAULT_DATA_THRESHOLD);
        let mut generated_markers = base
            .detect
            .generated_markers
            .unwrap_or_else(default_generated_markers);
        if let Some(extra) = local.detect.generated_markers {
            generated_markers.extend(extra);
        }

        // [rules]: a committed layer, a local layer, and — committed only —
        // the lock set. A value is either a bare severity string or the
        // inline-table form `{ severity = "error", locked = true }`.
        let mut rule_locks: Vec<String> = Vec::new();
        let mut rule_scopes: Vec<(String, RuleScope)> = Vec::new();
        let globs = |t: &toml::Table, key: &str| -> Vec<String> {
            t.get(key)
                .and_then(|v| v.as_array())
                .map(|a| {
                    a.iter()
                        .filter_map(|g| g.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default()
        };
        let parse_rules_table = |raw_rules: BTreeMap<String, toml::Value>,
                                 origin: &str,
                                 locks: Option<&mut Vec<String>>,
                                 scopes: &mut Vec<(String, RuleScope)>,
                                 warnings: &mut Vec<String>|
         -> Vec<RulesLayer> {
            if raw_rules.is_empty() {
                return Vec::new();
            }
            let mut lock_sink = locks;
            let entries: Vec<(String, String)> = raw_rules
                .into_iter()
                .map(|(k, v)| {
                    let value = match v {
                        toml::Value::String(s) => s,
                        toml::Value::Table(t) => {
                            let sev = t
                                .get("severity")
                                .and_then(|s| s.as_str())
                                .unwrap_or("")
                                .to_string();
                            if t.get("locked").and_then(|l| l.as_bool()) == Some(true) {
                                match lock_sink.as_deref_mut() {
                                    Some(sink) => sink.push(k.clone()),
                                    None => warnings.push(format!(
                                        "{origin}: [rules] '{k}': locks only apply from the \
                                         committed argot.toml — ignored"
                                    )),
                                }
                            }
                            let inc = globs(&t, "include");
                            let exc = globs(&t, "exclude");
                            if !inc.is_empty() || !exc.is_empty() {
                                scopes.push((
                                    k.clone(),
                                    RuleScope {
                                        include: inc,
                                        exclude: exc,
                                    },
                                ));
                            }
                            sev
                        }
                        other => other.to_string(),
                    };
                    (k, value)
                })
                .collect();
            vec![validate_layer_with(registry, &entries, origin, warnings)]
        };
        let rules_committed = parse_rules_table(
            base.rules,
            CONFIG_FILE,
            Some(&mut rule_locks),
            &mut rule_scopes,
            &mut warnings,
        );
        let rules_local = parse_rules_table(
            local.rules,
            LOCAL_CONFIG_FILE,
            None,
            &mut rule_scopes,
            &mut warnings,
        );
        rule_locks.retain(|l| {
            let known = registry.known_selector(l);
            if !known {
                warnings.push(format!(
                    "argot.toml: [rules] lock on unknown rule '{l}' — ignored"
                ));
            }
            known
        });

        // [update] / [fit]: scalars — local wins.
        let update_check = local.update.check.or(base.update.check).unwrap_or(true);
        let fit_auto_refresh = local
            .fit
            .auto_refresh
            .or(base.fit.auto_refresh)
            .unwrap_or(true);
        let fit_refresh_after = local
            .fit
            .refresh_after
            .or(base.fit.refresh_after)
            .map(|n| (n as usize).max(1))
            .unwrap_or(DEFAULT_FIT_REFRESH_AFTER);
        let fit_refresh_from = local
            .fit
            .refresh_from
            .or(base.fit.refresh_from)
            .map(|s| match s.as_str() {
                "default-branch" => FitRefreshFrom::DefaultBranch,
                "current-branch" => FitRefreshFrom::CurrentBranch,
                name if !name.trim().is_empty() => FitRefreshFrom::Branch(name.to_string()),
                _ => {
                    warnings.push(
                        "[fit] refresh-from: empty value — using \"default-branch\" (valid: \
                         \"default-branch\", \"current-branch\", or a branch name)"
                            .to_string(),
                    );
                    FitRefreshFrom::DefaultBranch
                }
            })
            .unwrap_or_default();

        // [[mute]] / [[migration]]: appended.
        let mut mutes = base.mute;
        mutes.extend(local.mute);
        let mut migrations = base.migration;
        migrations.extend(local.migration);

        ArgotConfig {
            exclude: ExcludeConfig {
                recommended,
                paths,
                check_only,
            },
            detect: DetectConfig {
                data_threshold,
                generated_markers,
            },
            rules_committed,
            rules_local,
            rule_scopes,
            rule_locks,
            update_check,
            fit_auto_refresh,
            fit_refresh_after,
            fit_refresh_from,
            mutes,
            migrations,
            from_file,
            degraded,
            warnings,
        }
    }

    /// Resolve the effective per-rule severities: registry defaults ⊕ config
    /// layers ⊕ the (already-validated) CLI `--rule` overrides.
    pub fn rule_settings(&self, cli_overrides: &RulesLayer) -> RuleSettings {
        self.rule_settings_with(Registry::builtin(), cli_overrides)
    }

    /// [`ArgotConfig::rule_settings`] against a run vocabulary — custom rules
    /// resolve from their manifest defaults through the same layers.
    pub fn rule_settings_with(
        &self,
        registry: &Registry,
        cli_overrides: &RulesLayer,
    ) -> RuleSettings {
        self.rule_settings_resolved(registry, cli_overrides).0
    }

    /// [`ArgotConfig::rule_settings_with`], also returning the refusal
    /// warnings (a runtime layer touching a locked rule) for stderr.
    pub fn rule_settings_resolved(
        &self,
        registry: &Registry,
        cli_overrides: &RulesLayer,
    ) -> (RuleSettings, Vec<String>) {
        let mut later = self.rules_local.clone();
        if !cli_overrides.is_empty() {
            later.push(cli_overrides.clone());
        }
        let mut warnings = Vec::new();
        let settings = RuleSettings::resolve_locked(
            registry,
            &self.rules_committed,
            &later,
            &self.rule_locks,
            &mut warnings,
        )
        .with_path_scopes(registry, &self.rule_scopes);
        (settings, warnings)
    }

    /// The resolved path-level suppression set (scope filter for check,
    /// calibration, inspect — the lock-step surface).
    pub fn path_suppressions(&self) -> PathSuppressions {
        PathSuppressions::from_parts(
            &self.exclude.recommended,
            &self.exclude.paths,
            &self.exclude.check_only,
            self.from_file,
        )
    }

    /// The durable mutes, validated and split into active/expired against
    /// `today` (`YYYY-MM-DD`).
    pub fn mutes(&self, today: &str) -> SuppressionsFile {
        self.mutes_with(Registry::builtin(), today)
    }

    /// [`ArgotConfig::mutes`] validating `[[mute]].rule` selectors against a
    /// run vocabulary (built-ins + the repo's custom rules).
    pub fn mutes_with(&self, registry: &Registry, today: &str) -> SuppressionsFile {
        build_mutes(registry, self.mutes.clone(), today)
    }

    /// The declared migrations (`[[migration]]`), validated — invalid entries
    /// warn and are skipped.
    pub fn migrations(&self) -> MigrationsFile {
        build_migrations(self.migrations.clone())
    }
}

/// The default `argot.toml` template `init`/`fit` writes — today's built-in
/// values, made explicit and editable. The `[exclude].recommended` and
/// `[detect].generated-markers` lists are rendered from the code defaults, so
/// the file and the code default can never drift.
pub fn default_toml() -> String {
    let render = |items: &[&str]| {
        items
            .iter()
            .map(|m| format!("  \"{m}\","))
            .collect::<Vec<_>>()
            .join("\n")
    };
    let recommended = render(crate::suppress::path_rules::DEFAULT_RECOMMENDED_PATTERNS);
    let check_only = render(crate::suppress::path_rules::DEFAULT_CHECK_ONLY_PATTERNS);
    let markers = render(DEFAULT_GENERATED_MARKERS);
    format!(
        "\
# argot.toml — argot's configuration, committed to version control.
#
# Written by `argot init`. Personal, uncommitted overrides go in
# argot.local.toml (gitignored): scalars there win, list entries append.
# Full reference: https://argot.tmonier.com/docs/configure/
# Writing for a coding agent? https://argot.tmonier.com/llms.txt

[exclude]
# The built-in argot:recommended set — directories and files that rarely carry a
# repo's authored voice. These are DROPPED silently: neither learned from nor
# checked. Edit freely: remove an entry to bring that dir back into check (e.g.
# drop \"test*/\" and \"*.test.*\" to have your tests checked — `check-only` below
# still keeps them from shaping the voice), or empty the list to rely on `paths`
# alone.
recommended = [
{recommended}
]

# Repo-specific excludes that shouldn't shape your voice (gitignore-style, one
# pattern per entry, add a trailing `# reason` comment). Unlike `recommended`,
# these are still scored but reported as muted, so every exclusion stays an
# auditable decision. Examples:
#   \"src/generated/\",   # protobuf / OpenAPI stubs
#   \"vendor/\",          # vendored third-party code
paths = []

# Paths that are CHECKED like any other, but never shape the voice. argot learns
# their dependency vocabulary — a library only your tests use stops reading as
# foreign — but not their style, so test phrasing never dilutes the model. On
# these paths the voice reports only `foreign-import`; every other rule (custom
# rules, layering, test integrity …) behaves normally.
# By default these are also in `recommended` above, so they aren't checked at all;
# remove them there to turn your tests into a guarded, non-teaching scope.
check-only = [
{check_only}
]

[detect]
# How argot spots code it should not learn from. `data-threshold` is the share
# of a file's non-blank lines that must be static data literals before the file
# counts as data, not authored voice.
data-threshold = {DEFAULT_DATA_THRESHOLD}

# A file whose head comments contain any of these (case-insensitive) is treated
# as generated and kept out of the voice model. Edit freely — trim ones you
# don't want, or add your own codegen banners. (Go/Rust/C# generated files are
# also caught by language-structural tells built into argot.)
generated-markers = [
{markers}
]

[fit]
# The background auto-refresh. When accepted history gains `refresh-after`
# commits touching in-scope source since the last fit, `check` refits in the
# background (committed code only, never your working tree).
auto-refresh = true
refresh-after = {DEFAULT_FIT_REFRESH_AFTER}
# What counts as accepted history. \"default-branch\" auto-detects your trunk
# (origin/HEAD, else main, else master) — nothing to fill in — and anchors the
# refresh at the merge-base with it, so a feature branch's own commits never
# train the voice; they stay the code under judgment. Name a branch (e.g.
# \"develop\") if your trunk is non-standard, or set \"current-branch\" to let
# refreshes learn whatever HEAD has.
refresh-from = \"default-branch\"

[rules]
# Per-rule severities: \"error\" (fails `argot check`), \"warn\" (reported, does
# not fail), or \"off\" (not run). Everything defaults to \"error\". Keys are rule
# names or whole groups — `argot rules` lists them; a rule-specific entry beats
# its group. Examples:
#   misplaced = \"warn\"     # report, but don't fail the check
#   semantic  = \"off\"      # disable the whole embedding-based group

# Durable, per-hit acceptances written by `argot mute <hash>` — a committed
# record of code you've decided is fine for this repo. Example:
#
# [[mute]]
# hash = \"a1b2c3d4e5f6\"
# reason = \"adopting axios repo-wide\"
# expires = \"2026-12-31\"   # optional

# Declared migrations — \"we're replacing X with Y\". New code using X raises
# the `superseded` rule (warn by default), Y stops reading as foreign, and
# `argot conventions` lists the files still to migrate. Effective immediately,
# no refit needed. argot also mines these from your accepted history; declare
# one to enforce a migration before history shows enough signal. Example:
#
# [[migration]]
# from = \"moment\"
# to = \"date-fns\"
# reason = \"Q2 date-handling refactor\"
# # kind = \"callee\"        # optional: \"import\" (default) or \"callee\"
"
    )
}

/// Read `argot.toml` as an editable document, falling back to the default
/// template when absent so writes always land in a well-formed file.
fn read_document(path: &Path) -> Result<DocumentMut, String> {
    let content = std::fs::read_to_string(path).unwrap_or_else(|_| default_toml());
    content
        .parse::<DocumentMut>()
        .map_err(|e| format!("{}: not valid TOML — {e}", path.display()))
}

/// Write `argot.toml` with the default template when absent (idempotent — an
/// existing file, hand-edited or not, is left untouched). Used by `fit`.
pub fn write_default_if_absent(repo_root: &Path) -> Result<bool, String> {
    let path = repo_root.join(CONFIG_FILE);
    if path.exists() {
        return Ok(false);
    }
    std::fs::write(&path, default_toml())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(true)
}

fn mute_table(rule: &SuppressionRule) -> Table {
    let mut t = Table::new();
    t["path"] = value(&rule.path);
    if let Some(s) = &rule.rule {
        t["rule"] = value(s);
    }
    if let Some(h) = &rule.hash {
        t["hash"] = value(h);
    }
    if let Some(e) = &rule.expires {
        t["expires"] = value(e);
    }
    t["reason"] = value(&rule.reason);
    t
}

/// Append one `[[mute]]` table to `argot.toml`, preserving every existing
/// section, comment, and hand edit (a textual DOM append, never a rewrite).
pub fn append_mute(repo_root: &Path, rule: &SuppressionRule) -> Result<(), String> {
    let path = repo_root.join(CONFIG_FILE);
    let mut doc = read_document(&path)?;
    let entry = doc
        .as_table_mut()
        .entry("mute")
        .or_insert_with(|| Item::ArrayOfTables(ArrayOfTables::new()));
    match entry {
        Item::ArrayOfTables(aot) => aot.push(mute_table(rule)),
        _ => {
            return Err(format!(
                "{}: `mute` is not a [[mute]] array",
                path.display()
            ))
        }
    }
    std::fs::write(&path, doc.to_string())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// Rewrite the `[[mute]]` array to exactly `kept`, preserving the rest of the
/// document (other sections, comments). Used by `review-mutes --prune`.
pub fn write_mutes(repo_root: &Path, kept: &[SuppressionRule]) -> Result<(), String> {
    let path = repo_root.join(CONFIG_FILE);
    let mut doc = read_document(&path)?;
    let mut aot = ArrayOfTables::new();
    for rule in kept {
        aot.push(mute_table(rule));
    }
    if aot.is_empty() {
        doc.as_table_mut().remove("mute");
    } else {
        doc["mute"] = Item::ArrayOfTables(aot);
    }
    std::fs::write(&path, doc.to_string())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))
}

