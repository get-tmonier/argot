/// The committed config file, at the repo root.
pub const CONFIG_FILE: &str = "argot.toml";
/// The gitignored personal-override file, at the repo root.
pub const LOCAL_CONFIG_FILE: &str = "argot.local.toml";

/// Resolved `[exclude]` section.
#[derive(Debug, Clone)]
pub struct ExcludeConfig {
    /// The built-in `argot:recommended` patterns (dropped silently). Editable —
    /// remove an entry to learn from that dir, empty it to disable the set.
    /// Default: [`default_recommended_patterns`].
    pub recommended: Vec<String>,
    /// Repo-specific exclude patterns (gitignore-style; scored but reported).
    pub paths: Vec<String>,
    /// Paths that are checked like any other, but never shape the voice:
    /// argot learns their dependency vocabulary, not their style.
    /// Default: [`default_check_only_patterns`].
    pub check_only: Vec<String>,
}

impl Default for ExcludeConfig {
    fn default() -> Self {
        ExcludeConfig {
            recommended: default_recommended_patterns(),
            paths: Vec::new(),
            check_only: default_check_only_patterns(),
        }
    }
}

/// File-level data-dominance threshold: a file whose top-level static data
/// literals cover more than this fraction of its non-blank lines is treated as
/// data, not authored voice. (The row-level value-dominance test stays a fixed
/// internal 0.80.)
pub const DEFAULT_DATA_THRESHOLD: f64 = 0.65;

/// Default `[fit].refresh-after`: accepted in-scope commits since the fit
/// before the voice counts as stale. A backstop, not a science constant —
/// tune it per repo in `argot.toml`.
pub const DEFAULT_FIT_REFRESH_AFTER: usize = 10;

/// `[fit].refresh-from` — which history the auto-refresh treats as the
/// repo's accepted voice.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum FitRefreshFrom {
    /// Anchor at the merge-base with the auto-detected default branch
    /// (`origin/HEAD`, else `main`, else `master`): a feature branch's own
    /// commits never train the voice (they're the code under judgment).
    #[default]
    DefaultBranch,
    /// A named trunk (`"develop"`, `"trunk"`) for repos whose accepted line
    /// isn't main/master. Same merge-base anchoring, explicit branch.
    Branch(String),
    /// Opt-out: treat whatever HEAD has as accepted (committed code only —
    /// the working tree still never trains the voice).
    CurrentBranch,
}

