use super::*;
use std::fs;
use std::path::PathBuf;

fn temp_repo(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("argot_suggest_{name}_{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

fn py_fn(i: usize) -> String {
    format!("def compute_{i}(a, b):\n    x = a + b\n    y = x * 2\n    return y - b\n")
}

fn generated_py(i: usize) -> String {
    format!("# Code generated by protoc. DO NOT EDIT.\n{}", py_fn(i))
}

fn data_py(i: usize) -> String {
    format!(
        "TABLE_{i} = {{\n    \"a\": 1,\n    \"b\": 2,\n    \"c\": 3,\n    \"d\": 4,\n    \"e\": 5,\n    \"f\": 6,\n}}\n"
    )
}

#[test]
fn generated_directory_is_suggested() {
    let dir = temp_repo("gen");
    fs::create_dir_all(dir.join("src/gen")).unwrap();
    for i in 0..4 {
        fs::write(dir.join(format!("src/gen/mod_{i}.py")), generated_py(i)).unwrap();
    }
    // Real code elsewhere must NOT be suggested.
    fs::write(dir.join("src/app.py"), py_fn(0)).unwrap();

    let s = suggest_ignores(&dir);
    assert_eq!(s.candidates.len(), 1, "only the generated dir");
    let c = &s.candidates[0];
    assert_eq!(c.path, "src/gen");
    assert_eq!(c.auto_generated, 4);
    assert_eq!(c.included, 0);
    assert_eq!(c.reason, "auto-generated");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn data_directory_is_suggested_with_reason() {
    // `locales` is not in argot:recommended, so a data-heavy one surfaces as
    // a candidate (a `fixtures/` dir, by contrast, is already excluded).
    let dir = temp_repo("data");
    fs::create_dir_all(dir.join("locales")).unwrap();
    for i in 0..3 {
        fs::write(dir.join(format!("locales/data_{i}.py")), data_py(i)).unwrap();
    }
    let s = suggest_ignores(&dir);
    let c = s
        .candidates
        .iter()
        .find(|c| c.path == "locales")
        .expect("locales candidate");
    assert_eq!(c.data_dominant, 3);
    assert_eq!(c.reason, "data-dominant");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn mixed_directory_below_ratio_is_not_suggested() {
    // 2 generated + 3 real code → 40% skipped, below SKIP_RATIO: ignoring it
    // would drop real voice, so argot stays silent and leaves the call to
    // the reader.
    let dir = temp_repo("mixed");
    fs::create_dir_all(dir.join("pkg")).unwrap();
    for i in 0..2 {
        fs::write(dir.join(format!("pkg/gen_{i}.py")), generated_py(i)).unwrap();
    }
    for i in 0..3 {
        fs::write(dir.join(format!("pkg/real_{i}.py")), py_fn(i)).unwrap();
    }
    let s = suggest_ignores(&dir);
    assert!(s.candidates.is_empty(), "mixed dir not suggested");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn topmost_qualifying_directory_wins() {
    // Every file under src/gen (and its subdirs) is generated, while src
    // also holds real code → collapse the generated subtree to src/gen
    // once, and never promote to src (which would drop the real code).
    let dir = temp_repo("topmost");
    fs::create_dir_all(dir.join("src/gen/inner")).unwrap();
    for i in 0..3 {
        fs::write(dir.join(format!("src/gen/a_{i}.py")), generated_py(i)).unwrap();
        fs::write(dir.join(format!("src/gen/inner/b_{i}.py")), generated_py(i)).unwrap();
    }
    fs::write(dir.join("src/app.py"), py_fn(0)).unwrap();
    let s = suggest_ignores(&dir);
    assert_eq!(s.candidates.len(), 1);
    assert_eq!(s.candidates[0].path, "src/gen");
    assert_eq!(s.candidates[0].supported_files, 6);
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn tiny_directory_below_min_files_is_ignored() {
    let dir = temp_repo("tiny");
    fs::create_dir_all(dir.join("g")).unwrap();
    for i in 0..2 {
        fs::write(dir.join(format!("g/x_{i}.py")), generated_py(i)).unwrap();
    }
    let s = suggest_ignores(&dir);
    assert!(s.candidates.is_empty(), "2-file dir below MIN_DIR_FILES");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn build_directories_are_not_traversed() {
    // Generated files inside node_modules/target must never surface — those
    // trees are pruned wholesale (speed), and are never authored source.
    let dir = temp_repo("builddir");
    fs::create_dir_all(dir.join("node_modules/pkg")).unwrap();
    fs::create_dir_all(dir.join("target/gen")).unwrap();
    for i in 0..4 {
        fs::write(
            dir.join(format!("node_modules/pkg/m_{i}.py")),
            generated_py(i),
        )
        .unwrap();
        fs::write(dir.join(format!("target/gen/g_{i}.py")), generated_py(i)).unwrap();
    }
    let s = suggest_ignores(&dir);
    assert!(
        s.candidates.is_empty(),
        "build/dep dirs pruned, not suggested"
    );
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn virtualenvs_are_pruned_by_marker() {
    // A virtualenv with a non-standard name is still pruned via its
    // `pyvenv.cfg` marker — structural, not name-based.
    let dir = temp_repo("venv");
    fs::create_dir_all(dir.join(".venv-work/site")).unwrap();
    fs::write(dir.join(".venv-work/pyvenv.cfg"), "home = /usr/bin\n").unwrap();
    for i in 0..4 {
        fs::write(
            dir.join(format!(".venv-work/site/m_{i}.py")),
            generated_py(i),
        )
        .unwrap();
    }
    let s = suggest_ignores(&dir);
    assert!(s.candidates.is_empty(), "venv pruned by pyvenv.cfg marker");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn already_ignored_directory_is_not_resuggested() {
    let dir = temp_repo("already");
    fs::create_dir_all(dir.join("gen")).unwrap();
    for i in 0..4 {
        fs::write(dir.join(format!("gen/mod_{i}.py")), generated_py(i)).unwrap();
    }
    fs::write(dir.join("argot.toml"), "[exclude]\npaths = [\"gen/\"]\n").unwrap();
    let s = suggest_ignores(&dir);
    assert!(
        s.candidates.iter().all(|c| c.path != "gen"),
        "gen/ already ignored → not re-suggested"
    );
    let _ = fs::remove_dir_all(&dir);
}
